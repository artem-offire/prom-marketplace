CREATE TABLE orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id         BIGINT                   NOT NULL,
    buyer_name        VARCHAR(200)             NOT NULL,
    buyer_phone       VARCHAR(32)              NOT NULL,
    buyer_email       VARCHAR(254),
    payment_method    VARCHAR(30)              NOT NULL,
    status            VARCHAR(20)              NOT NULL,
    total             NUMERIC(19,2)            NOT NULL,
    commission_amount NUMERIC(19,2)            NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_orders_status CHECK (status IN ('NEW', 'CONFIRMED', 'SHIPPED', 'COMPLETED', 'CANCELLED', 'RETURNED')),
    CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('CASH_ON_DELIVERY', 'ONLINE'))
);
CREATE INDEX ix_orders_seller_status ON orders (seller_id, status);

CREATE TABLE order_item (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id                 BIGINT        NOT NULL,
    product_id               BIGINT        NOT NULL,
    category_id              BIGINT        NOT NULL,
    title_snapshot           VARCHAR(300)  NOT NULL,
    unit_price               NUMERIC(19,2) NOT NULL,
    quantity                 INTEGER       NOT NULL,
    line_total               NUMERIC(19,2) NOT NULL,
    commission_rate_snapshot NUMERIC(5,2)  NOT NULL,
    commission_amount        NUMERIC(19,2) NOT NULL DEFAULT 0,
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0)
);
CREATE INDEX ix_order_item_order ON order_item (order_id);
