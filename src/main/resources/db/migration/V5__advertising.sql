CREATE TABLE ad_campaign (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id     BIGINT                   NOT NULL,
    name          VARCHAR(200)             NOT NULL,
    daily_budget  NUMERIC(19,2)            NOT NULL,
    spent_today   NUMERIC(19,2)            NOT NULL DEFAULT 0,
    spent_date    DATE                     NOT NULL,
    status        VARCHAR(20)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_ad_campaign_status CHECK (status IN ('ACTIVE', 'PAUSED'))
);
CREATE INDEX ix_ad_campaign_seller ON ad_campaign (seller_id);

CREATE TABLE ad_bid (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT                   NOT NULL,
    product_id  BIGINT                   NOT NULL,
    bid_amount  NUMERIC(19,2)            NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ad_bid_campaign FOREIGN KEY (campaign_id) REFERENCES ad_campaign (id),
    CONSTRAINT uq_ad_bid_campaign_product UNIQUE (campaign_id, product_id),
    CONSTRAINT ck_ad_bid_amount CHECK (bid_amount > 0)
);

CREATE TABLE ad_impression (
    id            UUID                     PRIMARY KEY,
    bid_id        BIGINT                   NOT NULL,
    campaign_id   BIGINT                   NOT NULL,
    product_id    BIGINT                   NOT NULL,
    category_id   BIGINT                   NOT NULL,
    slot_position INTEGER                  NOT NULL,
    ad_rank       NUMERIC(19,4)            NOT NULL,
    cpc           NUMERIC(19,2)            NOT NULL,
    session_id    VARCHAR(100),
    shown_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_ad_impression_campaign ON ad_impression (campaign_id);

CREATE TABLE ad_click (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    impression_id         UUID                     NOT NULL,
    session_id            VARCHAR(100),
    charged_amount        NUMERIC(19,2)            NOT NULL,
    status                VARCHAR(30)              NOT NULL,
    ledger_transaction_id UUID,
    clicked_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_ad_click_status CHECK (status IN ('CHARGED', 'UNCHARGED_NO_FUNDS', 'UNCHARGED_BUDGET', 'DUPLICATE'))
);
CREATE INDEX ix_ad_click_impression ON ad_click (impression_id);
