CREATE TABLE category (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(200)  NOT NULL,
    parent_id       BIGINT,
    commission_rate NUMERIC(5,2)  NOT NULL,
    min_bid         NUMERIC(19,2) NOT NULL,
    CONSTRAINT fk_category_parent FOREIGN KEY (parent_id) REFERENCES category (id),
    CONSTRAINT ck_category_commission CHECK (commission_rate >= 0 AND commission_rate <= 100),
    CONSTRAINT ck_category_min_bid CHECK (min_bid > 0)
);

CREATE TABLE product (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id     BIGINT                   NOT NULL,
    category_id   BIGINT                   NOT NULL,
    title         VARCHAR(300)             NOT NULL,
    description   VARCHAR(4000),
    price         NUMERIC(19,2)            NOT NULL,
    stock         INTEGER                  NOT NULL DEFAULT 0,
    status        VARCHAR(20)              NOT NULL,
    quality_score NUMERIC(3,2)             NOT NULL DEFAULT 0.50,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT ck_product_status CHECK (status IN ('DRAFT', 'ACTIVE', 'HIDDEN', 'ARCHIVED')),
    CONSTRAINT ck_product_price CHECK (price > 0)
);
CREATE INDEX ix_product_seller_status ON product (seller_id, status);
CREATE INDEX ix_product_category_status ON product (category_id, status);

