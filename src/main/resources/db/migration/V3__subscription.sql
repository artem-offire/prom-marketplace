CREATE TABLE plan (
    code                VARCHAR(20)   PRIMARY KEY,
    name                VARCHAR(100)  NOT NULL,
    monthly_price       NUMERIC(19,2) NOT NULL,
    yearly_price        NUMERIC(19,2) NOT NULL,
    product_limit       INTEGER       NOT NULL,
    marketplace_visible BOOLEAN       NOT NULL
);

CREATE TABLE plan_feature (
    plan_code VARCHAR(20) NOT NULL,
    feature   VARCHAR(40) NOT NULL,
    PRIMARY KEY (plan_code, feature),
    CONSTRAINT fk_plan_feature_plan FOREIGN KEY (plan_code) REFERENCES plan (code)
);

CREATE TABLE subscription (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id      BIGINT        NOT NULL,
    plan_code      VARCHAR(20)   NOT NULL,
    billing_period VARCHAR(10)   NOT NULL,
    price_paid     NUMERIC(19,2) NOT NULL,
    start_date     DATE          NOT NULL,
    end_date       DATE,
    status         VARCHAR(20)   NOT NULL,
    auto_renew     BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_subscription_plan FOREIGN KEY (plan_code) REFERENCES plan (code),
    CONSTRAINT ck_subscription_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT ck_subscription_period CHECK (billing_period IN ('MONTHLY', 'YEARLY'))
);
CREATE INDEX ix_subscription_seller_status ON subscription (seller_id, status);

