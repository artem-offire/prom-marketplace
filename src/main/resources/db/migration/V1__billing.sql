CREATE TABLE ledger_account (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(100)   NOT NULL,
    account_type VARCHAR(20)    NOT NULL,
    seller_id    BIGINT,
    balance      NUMERIC(19,2)  NOT NULL DEFAULT 0,
    version      BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_ledger_account_code UNIQUE (code),
    CONSTRAINT ck_ledger_account_type CHECK (account_type IN ('ASSET', 'LIABILITY', 'REVENUE'))
);
CREATE INDEX ix_ledger_account_seller ON ledger_account (seller_id);

CREATE TABLE ledger_transaction (
    id              UUID                     PRIMARY KEY,
    tx_type         VARCHAR(40)              NOT NULL,
    idempotency_key VARCHAR(150)             NOT NULL,
    reference_type  VARCHAR(40),
    reference_id    VARCHAR(100),
    description     VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_ledger_transaction_idem UNIQUE (idempotency_key)
);

CREATE TABLE ledger_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id UUID          NOT NULL,
    account_id     BIGINT        NOT NULL,
    direction      VARCHAR(10)   NOT NULL,
    amount         NUMERIC(19,2) NOT NULL,
    CONSTRAINT fk_ledger_entry_tx FOREIGN KEY (transaction_id) REFERENCES ledger_transaction (id),
    CONSTRAINT fk_ledger_entry_account FOREIGN KEY (account_id) REFERENCES ledger_account (id),
    CONSTRAINT ck_ledger_entry_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_entry_amount CHECK (amount > 0)
);
CREATE INDEX ix_ledger_entry_tx ON ledger_entry (transaction_id);
CREATE INDEX ix_ledger_entry_account ON ledger_entry (account_id);

